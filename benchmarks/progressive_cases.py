def _case(
    task_id: str,
    repository: str,
    family: str,
    execution: str,
    retrieval: str,
    prompt: str,
    required: list[list[str]],
    *,
    capability_path: list[str] | None = None,
    probe_terms: list[list[str]] | None = None,
    reasoning: str | None = None,
    calibration: bool = False,
) -> dict[str, object]:
    # Active event routing is independent of the rejected capability tree.
    # capability_path remains frozen experiment metadata only.
    expected_reasoning = reasoning or "NONE"
    retrieval_mode = {
        "R0": "TARGETED",
        "R1": "BOUNDED",
        "R2": "STRUCTURAL",
        "R3": "STRUCTURAL",
    }[retrieval]
    return {
        "task_id": task_id,
        "repository": repository,
        "family": family,
        "expected_execution": execution,
        "expected_retrieval": retrieval,
        "capability_path": capability_path or [],
        "expected_reasoning": expected_reasoning,
        "expected_retrieval_mode": retrieval_mode,
        "prompt": prompt,
        "required": required,
        "probe_terms": probe_terms or [],
        "calibration": calibration,
    }


